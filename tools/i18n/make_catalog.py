"""Builds src/core/Translations.inc from tools/i18n/catalog/*.txt (D70).

Each catalog file holds blocks separated by blank lines, one line per language:

    en: Icon size
    fr: Taille des icônes
    es: Tamaño de los iconos
    zh: 图标大小
    hi: आइकन का आकार

`en` is the key: the exact English text in the code. `\\n` is a line break, `\\t` a tab, `\\\\` a backslash. A
missing or empty language falls back to English at run time. The check refuses duplicates, and translations whose
{} placeholders or & access key differ from the English, so that a translation can never break a format.

  python tools/i18n/make_catalog.py            # writes src/core/Translations.inc
  python tools/i18n/make_catalog.py --check    # only checks; non-zero exit on a problem
"""
import pathlib
import re
import sys

LANGUAGES = ['en', 'fr', 'es', 'zh', 'hi']
ROOT = pathlib.Path(__file__).resolve().parents[2]
CATALOG = ROOT / 'tools' / 'i18n' / 'catalog'
OUTPUT = ROOT / 'src' / 'core' / 'Translations.inc'


def unescape(value):
    out, i = [], 0
    while i < len(value):
        c = value[i]
        if c == '\\' and i + 1 < len(value):
            nxt = value[i + 1]
            out.append({'n': '\n', 't': '\t', '\\': '\\', 'r': '\r'}.get(nxt, '\\' + nxt))
            i += 2
            continue
        out.append(c)
        i += 1
    return ''.join(out)


def literal(text):
    parts = []
    for ch in text:
        code = ord(ch)
        if ch == '\\':
            parts.append('\\\\')
        elif ch == '"':
            parts.append('\\"')
        elif ch == '\n':
            parts.append('\\n')
        elif ch == '\r':
            parts.append('\\r')
        elif ch == '\t':
            parts.append('\\t')
        elif 32 <= code < 127:
            parts.append(ch)
        elif code <= 0xFFFF:
            parts.append('\\u%04X' % code)
        else:
            parts.append('\\U%08X' % code)
    return 'L"' + ''.join(parts) + '"'


def read_catalog():
    entries, problems = [], []
    for path in sorted(CATALOG.glob('*.txt')):
        blocks = re.split(r'\n\s*\n', path.read_text(encoding='utf-8').replace('\r\n', '\n'))
        for block in blocks:
            lines = [line for line in block.split('\n') if line.strip() and not line.startswith('#')]
            if not lines:
                continue
            entry = {}
            for line in lines:
                match = re.match(r'^(en|fr|es|zh|hi): ?(.*)$', line)
                if not match:
                    problems.append(f'{path.name}: unreadable line {line!r}')
                    continue
                entry[match.group(1)] = unescape(match.group(2))
            if 'en' not in entry:
                problems.append(f'{path.name}: block without en: {lines[0]!r}')
                continue
            entry['_file'] = path.name
            entries.append(entry)
    return entries, problems


def access_key(text):
    """Whether `text` marks an access key: '&' before a character, not '&&' nor a plain ' & '."""
    return re.search(r'&(?![\s&])', text.replace('&&', '')) is not None


def placeholders(text):
    return sorted(re.findall(r'\{[^{}]*\}', text.replace('{{', '').replace('}}', '')))


def check(entries):
    problems, seen = [], {}
    for entry in entries:
        key = entry['en']
        if key in seen:
            problems.append(f"duplicate {key!r} in {entry['_file']} and {seen[key]}")
            continue
        seen[key] = entry['_file']
        for language in LANGUAGES[1:]:
            text = entry.get(language, '')
            if not text:
                continue
            if placeholders(text) != placeholders(key):
                problems.append(f'{language} placeholders differ for {key!r}')
            if access_key(key) != access_key(text):
                problems.append(f'{language} access key (&) differs for {key!r}')
    return problems


def main():
    entries, problems = read_catalog()
    problems += check(entries)
    for problem in problems:
        print(problem, file=sys.stderr)
    if problems:
        return 1
    if '--check' in sys.argv:
        print(f'{len(entries)} texts, no problem')
        return 0
    seen = set()
    lines = ['// SPDX-License-Identifier: MIT', '// Copyright (c) 2026 Ibrahim Bouillet',
             '// Generated by tools/i18n/make_catalog.py from tools/i18n/catalog/*.txt. Do not edit by hand.',
             '// One entry per interface text: English (the key), French, Spanish, Chinese (Simplified), Hindi.']
    missing = {language: 0 for language in LANGUAGES[1:]}
    for entry in entries:
        if entry['en'] in seen:
            continue
        seen.add(entry['en'])
        for language in LANGUAGES[1:]:
            if not entry.get(language):
                missing[language] += 1
        lines.append('{{' + ', '.join(literal(entry.get(language, '')) for language in LANGUAGES) + '}},')
    OUTPUT.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    print(f'{len(seen)} texts written to {OUTPUT.relative_to(ROOT)}; untranslated: ' +
          ', '.join(f'{k} {v}' for k, v in missing.items()))
    return 0


if __name__ == '__main__':
    sys.exit(main())
